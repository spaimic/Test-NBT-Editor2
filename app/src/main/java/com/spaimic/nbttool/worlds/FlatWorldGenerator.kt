package com.spaimic.nbttool.worlds

import com.spaimic.nbttool.nbt.NbtIO
import com.spaimic.nbttool.nbt.NbtTag
import org.json.JSONArray
import org.json.JSONObject

/** One layer of a custom flat world, bottom-to-top order (index 0 = touches bedrock). */
data class FlatLayer(var blockName: String, var count: Int)

/**
 * Bedrock stores flat-world layers as a JSON string (not nested NBT) inside
 * level.dat's "FlatWorldLayers" tag — this predates any in-game UI for
 * customizing it; hand-editing this exact JSON via an NBT editor is the
 * long-standing community technique. Setting it (plus `Generator`=2) only
 * affects how NEWLY generated chunks are created — it can't retroactively
 * reshape terrain that's already been explored/generated.
 */
object FlatWorldGenerator {

    const val GENERATOR_FLAT = 2

    fun toJson(
        layers: List<FlatLayer>,
        biomeId: Int = 1,
        presetId: String = "Overworld",
        worldVersion: String = "version.post_1_18",
        encodingVersion: Int = 6
    ): String {
        val layersArray = JSONArray()
        for (l in layers) {
            layersArray.put(JSONObject().apply {
                put("block_name", l.blockName)
                put("count", l.count)
            })
        }
        return JSONObject().apply {
            put("biome_id", biomeId)
            put("block_layers", layersArray)
            put("encoding_version", encodingVersion)
            put("preset_id", presetId)
            put("world_version", worldVersion)
        }.toString()
    }

    /**
     * Builds a complete, from-scratch level.dat for a brand-new flat world — every
     * field below (except LevelName, FlatWorldLayers, RandomSeed, LastPlayed) is
     * copied verbatim from a known-working reference level.dat (generated by
     * another Bedrock world-creator app) rather than guessed, since Minecraft
     * expects a large, specific set of game-rule/settings fields to exist even
     * for a "new" world it hasn't loaded yet.
     */
    fun buildNewWorldLevelDat(levelName: String, layers: List<FlatLayer>): NbtIO.LevelDat {
        fun b(v: Int) = NbtTag.Byte(v.toByte())
        fun i(v: Int) = NbtTag.Int(v)
        fun l(v: Long) = NbtTag.Long(v)
        fun f(v: Float) = NbtTag.Float(v)
        fun s(v: String) = NbtTag.Str(v)
        fun intList(vararg v: Int) = NbtTag.ListTag(3, v.map { NbtTag.Int(it) as NbtTag }.toMutableList())

        val abilities = NbtTag.Compound(linkedMapOf(
            "attackmobs" to b(1), "attackplayers" to b(1), "build" to b(1), "doorsandswitches" to b(1),
            "flySpeed" to f(0.05000000074505806f), "flying" to b(0), "instabuild" to b(0), "invulnerable" to b(0),
            "lightning" to b(0), "mayfly" to b(0), "mine" to b(1), "op" to b(0), "opencontainers" to b(1),
            "teleport" to b(0), "verticalFlySpeed" to f(1.0f), "walkSpeed" to f(0.10000000149011612f)
        ))
        val experiments = NbtTag.Compound(linkedMapOf(
            "experiments_ever_used" to b(0), "saved_with_toggled_experiments" to b(0)
        ))

        val now = System.currentTimeMillis() / 1000
        val seed = kotlin.random.Random.nextLong()

        val root = LinkedHashMap<String, NbtTag>()
        root["BiomeOverride"] = s("minecraft:minecraft:")
        root["CenterMapsToOrigin"] = b(0)
        root["ConfirmedPlatformLockedContent"] = b(0)
        root["Difficulty"] = i(2)
        root["FlatWorldLayers"] = s(toJson(layers))
        root["ForceGameType"] = b(0)
        root["GameType"] = i(1)
        root["Generator"] = i(GENERATOR_FLAT)
        root["HasUncompleteWorldFileOnDisk"] = b(0)
        root["InventoryVersion"] = s("1.21.101")
        root["IsHardcore"] = b(0)
        root["LANBroadcast"] = b(1)
        root["LANBroadcastIntent"] = b(1)
        root["LastPlayed"] = l(now)
        root["LevelName"] = s(levelName)
        root["LimitedWorldOriginX"] = i(0)
        root["LimitedWorldOriginY"] = i(32767)
        root["LimitedWorldOriginZ"] = i(0)
        root["MinimumCompatibleClientVersion"] = intList(1, 21, 100, 0, 0)
        root["MultiplayerGame"] = b(1)
        root["MultiplayerGameIntent"] = b(1)
        root["NetherScale"] = i(8)
        root["NetworkVersion"] = i(827)
        root["Platform"] = i(2)
        root["PlatformBroadcastIntent"] = i(2)
        root["PlayerHasDied"] = b(0)
        root["RandomSeed"] = l(seed)
        root["SpawnV1Villagers"] = b(0)
        root["SpawnX"] = i(0)
        root["SpawnY"] = i(32767)
        root["SpawnZ"] = i(0)
        root["StorageVersion"] = i(10)
        root["Time"] = l(144)
        root["WorldVersion"] = i(1)
        root["XBLBroadcastIntent"] = i(2)
        root["abilities"] = abilities
        root["baseGameVersion"] = s("*")
        root["bonusChestEnabled"] = b(0)
        root["bonusChestSpawned"] = b(0)
        root["cheatsEnabled"] = b(0)
        root["commandblockoutput"] = b(1)
        root["commandblocksenabled"] = b(1)
        root["commandsEnabled"] = b(0)
        root["currentTick"] = l(144)
        root["daylightCycle"] = i(0)
        root["dodaylightcycle"] = b(1)
        root["doentitydrops"] = b(1)
        root["dofiretick"] = b(1)
        root["doimmediaterespawn"] = b(0)
        root["doinsomnia"] = b(1)
        root["dolimitedcrafting"] = b(0)
        root["domobloot"] = b(1)
        root["domobspawning"] = b(1)
        root["dotiledrops"] = b(1)
        root["doweathercycle"] = b(1)
        root["drowningdamage"] = b(1)
        root["editorWorldType"] = i(0)
        root["eduOffer"] = i(0)
        root["educationFeaturesEnabled"] = b(0)
        root["experiments"] = experiments
        root["falldamage"] = b(1)
        root["firedamage"] = b(1)
        root["freezedamage"] = b(1)
        root["functioncommandlimit"] = i(10000)
        root["hasBeenLoadedInCreative"] = b(1)
        root["hasLockedBehaviorPack"] = b(0)
        root["hasLockedResourcePack"] = b(0)
        root["immutableWorld"] = b(0)
        root["isCreatedInEditor"] = b(0)
        root["isExportedFromEditor"] = b(0)
        root["isFromLockedTemplate"] = b(0)
        root["isFromWorldTemplate"] = b(0)
        root["isRandomSeedAllowed"] = b(0)
        root["isSingleUseWorld"] = b(0)
        root["isWorldTemplateOptionLocked"] = b(0)
        root["keepinventory"] = b(0)
        root["lastOpenedWithVersion"] = intList(1, 21, 101, 1, 0)
        root["lightningLevel"] = f(0.0f)
        root["lightningTime"] = i(141346)
        root["limitedWorldDepth"] = i(16)
        root["limitedWorldWidth"] = i(16)
        root["locatorbar"] = b(1)
        root["maxcommandchainlength"] = i(65535)
        root["mobgriefing"] = b(1)
        root["naturalregeneration"] = b(1)
        root["permissionsLevel"] = i(0)
        root["playerPermissionsLevel"] = i(1)
        root["playerssleepingpercentage"] = i(100)
        root["prid"] = s("")
        root["projectilescanbreakblocks"] = b(1)
        root["pvp"] = b(1)
        root["rainLevel"] = f(0.0f)
        root["rainTime"] = i(121345)
        root["randomtickspeed"] = i(1)
        root["recipesunlock"] = b(1)
        root["requiresCopiedPackRemovalCheck"] = b(0)
        root["respawnblocksexplode"] = b(1)
        root["sendcommandfeedback"] = b(1)
        root["serverChunkTickRange"] = i(4)
        root["showbordereffect"] = b(1)
        root["showcoordinates"] = b(0)
        root["showdaysplayed"] = b(0)
        root["showdeathmessages"] = b(1)
        root["showrecipemessages"] = b(1)
        root["showtags"] = b(1)
        root["spawnMobs"] = b(1)
        root["spawnradius"] = i(10)
        root["startWithMapEnabled"] = b(0)
        root["texturePacksRequired"] = b(0)
        root["tntexplodes"] = b(1)
        root["tntexplosiondropdecay"] = b(0)
        root["useMsaGamertagsOnly"] = b(0)
        root["worldStartCount"] = l(4294967294L)
        root["world_policies"] = NbtTag.Compound(LinkedHashMap())

        return NbtIO.LevelDat(10, NbtTag.Compound(root))
    }

    /** Parses an existing FlatWorldLayers JSON string back into editable layers, if present/valid. */
    fun fromJson(json: String): List<FlatLayer>? = try {
        val root = JSONObject(json)
        val arr = root.getJSONArray("block_layers")
        (0 until arr.length()).map { i ->
            val entry = arr.getJSONObject(i)
            FlatLayer(entry.getString("block_name"), entry.getInt("count"))
        }
    } catch (e: Exception) {
        null
    }
}
